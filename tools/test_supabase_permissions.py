"""
tools/test_supabase_permissions.py

Pre-flight permission auditor for Supabase PostgreSQL.
Tests all required DDL, DML, RLS, and Sequence privileges using a temporary table.
Safely cleans up afterwards without touching application data.
Masks credentials to ensure zero sensitive data is logged.
"""

import os
import sys
from sqlalchemy import create_engine, text

CURRENT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(CURRENT_DIR)

try:
    from dotenv import load_dotenv
    load_dotenv(os.path.join(PROJECT_ROOT, ".env"))
    load_dotenv(os.path.join(PROJECT_ROOT, "backend", ".env"))
except ImportError:
    pass

def normalize_db_url(url: str) -> str:
    if url.startswith("postgres://"):
        return url.replace("postgres://", "postgresql+psycopg://", 1)
    elif url.startswith("postgresql://") and not url.startswith("postgresql+"):
        return url.replace("postgresql://", "postgresql+psycopg://", 1)
    return url

def test_permissions(target_url: str) -> bool:
    target_url = normalize_db_url(target_url)
    safe_target = target_url.split("@")[-1].split("/")[0] if "@" in target_url else "target"
    print("=" * 75)
    print(" SUPABASE POSTGRESQL PERMISSIONS AUDIT")
    print("=" * 75)
    print(f" Target Host: {safe_target}")
    print("-" * 75)

    connect_args = {}
    if "postgresql" in target_url:
        connect_args["prepare_threshold"] = None

    try:
        engine = create_engine(target_url, pool_recycle=300, pool_pre_ping=True, connect_args=connect_args)
        with engine.connect() as conn:
            conn.execute(text("SELECT 1"))
        print(" [PASS] Connection handshake: Successfully connected.")
    except Exception as e:
        print(f" [FAIL] Connection handshake: {e}")
        return False

    perm_results = []
    
    def check_perm(name, sql):
        try:
            with engine.begin() as conn:
                conn.execute(text(sql))
            print(f" [PASS] Permission: {name}")
            perm_results.append((name, True))
        except Exception as e:
            print(f" [FAIL] Permission: {name} ({e})")
            perm_results.append((name, False))

    # 1. CREATE TABLE
    check_perm("Create Table", """
        CREATE TABLE IF NOT EXISTS _migration_perm_check (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            test_val VARCHAR(100)
        );
    """)

    # 2. CREATE INDEX
    check_perm("Create Index", """
        CREATE INDEX IF NOT EXISTS ix_perm_check_val ON _migration_perm_check (test_val);
    """)

    # 3. ENABLE RLS
    check_perm("Enable Row Level Security (RLS)", """
        ALTER TABLE _migration_perm_check ENABLE ROW LEVEL SECURITY;
    """)

    # 4. CREATE POLICY
    check_perm("Create Security Policy", """
        DO $$
        BEGIN
            IF NOT EXISTS (
                SELECT 1 FROM pg_policies WHERE tablename = '_migration_perm_check' AND policyname = 'perm_test_policy'
            ) THEN
                CREATE POLICY perm_test_policy ON _migration_perm_check FOR SELECT USING (true);
            END IF;
        END $$;
    """)

    # 5. INSERT
    check_perm("Insert Records (DML)", """
        INSERT INTO _migration_perm_check (test_val) VALUES ('perm_test_ok');
    """)

    # 6. SELECT
    check_perm("Select Records (DML)", """
        SELECT COUNT(*) FROM _migration_perm_check;
    """)

    # 7. UPDATE SEQUENCE (setval)
    check_perm("Sequence Synchronization (setval)", """
        SELECT setval(pg_get_serial_sequence('_migration_perm_check', 'id'), 10, true);
    """)

    # 8. DROP TABLE (Cleanup)
    check_perm("Drop Temporary Table (Cleanup)", """
        DROP TABLE IF EXISTS _migration_perm_check CASCADE;
    """)

    print("-" * 75)
    all_passed = all(p[1] for p in perm_results)
    if all_passed:
        print(" [SUCCESS] All 8 required Supabase PostgreSQL privileges are CONFIRMED.")
    else:
        print(" [WARNING] One or more permission checks failed. Review details above.")
    print("=" * 75)
    return all_passed

if __name__ == "__main__":
    url = os.getenv("TARGET_DATABASE_URL") or os.getenv("DATABASE_URL")
    if not url or "sqlite" in url:
        print("[Notice] TARGET_DATABASE_URL not set. Set it before running permission audit.")
        sys.exit(1)
    ok = test_permissions(url)
    sys.exit(0 if ok else 1)

