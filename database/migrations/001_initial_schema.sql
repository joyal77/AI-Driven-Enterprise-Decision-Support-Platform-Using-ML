-- PostgreSQL Schema Migration for Supabase Target Database
-- ==============================================================================

-- 1. Users Table (Platform Administrators and Executives)
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(100) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(50) DEFAULT 'admin',
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_users_email ON users (email);

-- 2. Customers Table (E-Commerce Customer Metrics & Churn Attributes)
CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_customer_id VARCHAR(50) UNIQUE NOT NULL,
    signup_date DATE NULL,
    customer_age DOUBLE PRECISION NULL,
    gender VARCHAR(50) NULL,
    city_tier VARCHAR(50) NULL,
    membership_status VARCHAR(50) NULL,
    days_since_last_purchase DOUBLE PRECISION NULL,
    total_orders_lifetime INTEGER NULL,
    orders_last_30d INTEGER NULL,
    orders_prev_30_to_60d DOUBLE PRECISION NULL,
    total_spend_inr VARCHAR(100) NULL,
    avg_order_value DOUBLE PRECISION NULL,
    preferred_category VARCHAR(100) NULL,
    sessions_last_30d INTEGER NULL,
    avg_session_duration_min DOUBLE PRECISION NULL,
    cart_abandonments_last_30d INTEGER NULL,
    search_queries_last_30d DOUBLE PRECISION NULL,
    return_count INTEGER NULL,
    return_rate DOUBLE PRECISION NULL,
    cancellations_count INTEGER NULL,
    late_deliveries_count INTEGER NULL,
    customer_service_tickets INTEGER NULL,
    avg_rating_given DOUBLE PRECISION NULL,
    preferred_payment_mode VARCHAR(50) NULL,
    ground_truth_churn INTEGER NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_customers_source_customer_id ON customers (source_customer_id);
CREATE INDEX IF NOT EXISTS ix_customers_city_tier ON customers (city_tier);
CREATE INDEX IF NOT EXISTS ix_customers_membership_status ON customers (membership_status);
CREATE INDEX IF NOT EXISTS ix_customers_days_since_last_purchase ON customers (days_since_last_purchase);
CREATE INDEX IF NOT EXISTS ix_customers_preferred_category ON customers (preferred_category);
CREATE INDEX IF NOT EXISTS ix_customers_ground_truth_churn ON customers (ground_truth_churn);

-- 3. Store Users Table (Multi-Role Authentication: Customer, PM, Admin)
CREATE TABLE IF NOT EXISTS store_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL,
    customer_id BIGINT NULL REFERENCES customers(id) ON DELETE SET NULL,
    full_name VARCHAR(150) NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_store_users_username ON store_users (username);
CREATE INDEX IF NOT EXISTS ix_store_users_role ON store_users (role);
CREATE INDEX IF NOT EXISTS ix_store_users_customer_id ON store_users (customer_id);

-- 4. Products Table (Catalog & Inventory)
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(50) UNIQUE NULL,
    title VARCHAR(200) NOT NULL,
    product_name VARCHAR(200) NULL,
    category VARCHAR(100) NOT NULL,
    price DOUBLE PRECISION NOT NULL,
    original_price DOUBLE PRECISION NULL,
    stock_quantity INTEGER DEFAULT 100,
    rating DOUBLE PRECISION DEFAULT 4.5,
    rating_count INTEGER DEFAULT 120,
    image_url VARCHAR(500) NULL,
    description TEXT NULL,
    is_prime INTEGER DEFAULT 1,
    is_active INTEGER DEFAULT 1,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_products_sku ON products (sku);
CREATE INDEX IF NOT EXISTS ix_products_title ON products (title);
CREATE INDEX IF NOT EXISTS ix_products_category ON products (category);

-- 5. Orders Table (E-Commerce Purchase Records)
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(50) UNIQUE NULL,
    customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    order_date TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    order_amount DOUBLE PRECISION NOT NULL,
    subtotal DOUBLE PRECISION NULL,
    tax_amount DOUBLE PRECISION DEFAULT 0.0,
    shipping_amount DOUBLE PRECISION DEFAULT 0.0,
    discount DOUBLE PRECISION DEFAULT 0.0,
    payment_mode VARCHAR(50) DEFAULT 'UPI',
    order_status VARCHAR(50) DEFAULT 'Confirmed',
    shipping_address TEXT NULL,
    return_status VARCHAR(50) DEFAULT 'None',
    voucher_code VARCHAR(50) NULL,
    wallet_credit_used DOUBLE PRECISION DEFAULT 0.0,
    free_shipping_applied INTEGER DEFAULT 0
);
CREATE INDEX IF NOT EXISTS ix_orders_order_number ON orders (order_number);
CREATE INDEX IF NOT EXISTS ix_orders_customer_id ON orders (customer_id);
CREATE INDEX IF NOT EXISTS ix_orders_order_status ON orders (order_status);

-- 6. Order Items Table
CREATE TABLE IF NOT EXISTS order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    quantity INTEGER DEFAULT 1,
    unit_price DOUBLE PRECISION NOT NULL,
    total_price DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_order_items_order_id ON order_items (order_id);
CREATE INDEX IF NOT EXISTS ix_order_items_product_id ON order_items (product_id);

-- 7. Cart Items Table (Isolated Per-Customer Cart)
CREATE TABLE IF NOT EXISTS cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    quantity INTEGER DEFAULT 1,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_cart_items_customer_id ON cart_items (customer_id);
CREATE INDEX IF NOT EXISTS ix_cart_items_product_id ON cart_items (product_id);

-- 8. Churn Predictions Table (ML Classification & SHAP Dumps)
CREATE TABLE IF NOT EXISTS churn_predictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    churn_probability DOUBLE PRECISION NOT NULL,
    churn_prediction INTEGER NOT NULL,
    risk_category VARCHAR(50) NOT NULL,
    model_version VARCHAR(50) DEFAULT 'Random Forest v1.0',
    prediction_timestamp TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    shap_explanation TEXT NULL,
    root_causes TEXT NULL,
    recommendations TEXT NULL
);
CREATE INDEX IF NOT EXISTS ix_churn_predictions_customer_id ON churn_predictions (customer_id);
CREATE INDEX IF NOT EXISTS ix_churn_predictions_risk_category ON churn_predictions (risk_category);

-- 9. Retention Recommendations Table
CREATE TABLE IF NOT EXISTS retention_recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    recommendation_type VARCHAR(100) NOT NULL,
    recommendation_description TEXT NOT NULL,
    status VARCHAR(50) DEFAULT 'Pending',
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_retention_recommendations_customer_id ON retention_recommendations (customer_id);
CREATE INDEX IF NOT EXISTS ix_retention_recommendations_status ON retention_recommendations (status);

-- 10. Prediction Batches Table
CREATE TABLE IF NOT EXISTS prediction_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_status VARCHAR(50) DEFAULT 'Completed',
    total_customers INTEGER DEFAULT 0,
    processed_customers INTEGER DEFAULT 0,
    failed_customers INTEGER DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_prediction_batches_batch_status ON prediction_batches (batch_status);

-- 11. Data Integrity Audit Log Table
CREATE TABLE IF NOT EXISTS data_integrity_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_type VARCHAR(100) NOT NULL,
    customer_id VARCHAR(50) NULL,
    severity VARCHAR(20) DEFAULT 'INFO',
    expected_value TEXT NULL,
    observed_value TEXT NULL,
    resolution_status VARCHAR(50) DEFAULT 'Reconciled',
    details TEXT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_data_integrity_audit_log_check_type ON data_integrity_audit_log (check_type);
CREATE INDEX IF NOT EXISTS ix_data_integrity_audit_log_customer_id ON data_integrity_audit_log (customer_id);
CREATE INDEX IF NOT EXISTS ix_data_integrity_audit_log_severity ON data_integrity_audit_log (severity);
CREATE INDEX IF NOT EXISTS ix_data_integrity_audit_log_resolution_status ON data_integrity_audit_log (resolution_status);

-- 12. Customer Retention Perks Table
CREATE TABLE IF NOT EXISTS customer_retention_perks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    campaign_id VARCHAR(100) NOT NULL,
    title VARCHAR(255) NOT NULL,
    perk_type VARCHAR(50) NOT NULL,
    perk_value DOUBLE PRECISION DEFAULT 0.0,
    coupon_code VARCHAR(50) NULL,
    free_shipping INTEGER DEFAULT 0,
    status VARCHAR(50) DEFAULT 'Approved',
    coupon_used INTEGER DEFAULT 0,
    shipping_used INTEGER DEFAULT 0,
    used_order_id BIGINT NULL REFERENCES orders(id) ON DELETE SET NULL,
    used_at TIMESTAMP WITHOUT TIME ZONE NULL,
    is_single_use INTEGER DEFAULT 1,
    action_summary TEXT NULL,
    root_cause_driver VARCHAR(255) NULL,
    channel VARCHAR(100) NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_customer_retention_perks_customer_id ON customer_retention_perks (customer_id);
CREATE INDEX IF NOT EXISTS ix_customer_retention_perks_campaign_id ON customer_retention_perks (campaign_id);
CREATE INDEX IF NOT EXISTS ix_customer_retention_perks_status ON customer_retention_perks (status);

-- 13. Customer Account Notifications Table
CREATE TABLE IF NOT EXISTS customer_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    campaign_id VARCHAR(100) NULL,
    title VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    image_url VARCHAR(500) NULL,
    notification_type VARCHAR(50) DEFAULT 'retention_perk',
    navigation_target VARCHAR(255) DEFAULT '/store/cart',
    channel VARCHAR(100) DEFAULT 'Storefront Notification',
    sender VARCHAR(150) DEFAULT 'SmartCart Concierge',
    coupon_code VARCHAR(50) NULL,
    perk_type VARCHAR(50) NULL,
    perk_value DOUBLE PRECISION DEFAULT 0.0,
    is_read INTEGER DEFAULT 0,
    dispatch_status VARCHAR(50) DEFAULT 'Delivered',
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_customer_notifications_customer_id ON customer_notifications (customer_id);
CREATE INDEX IF NOT EXISTS ix_customer_notifications_campaign_id ON customer_notifications (campaign_id);

-- 14. Customer Retention Perk Redemptions Table
CREATE TABLE IF NOT EXISTS customer_perk_redemptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    order_number VARCHAR(50) NOT NULL,
    perk_id BIGINT NULL REFERENCES customer_retention_perks(id) ON DELETE SET NULL,
    campaign_id VARCHAR(100) NULL,
    benefit_type VARCHAR(50) NOT NULL,
    coupon_code VARCHAR(50) NULL,
    discount_amount DOUBLE PRECISION DEFAULT 0.0,
    redemption_date TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(50) DEFAULT 'Redeemed',
    CONSTRAINT uq_cust_coupon_benefit_redemption UNIQUE (customer_id, coupon_code, benefit_type)
);
CREATE INDEX IF NOT EXISTS ix_customer_perk_redemptions_customer_id ON customer_perk_redemptions (customer_id);
CREATE INDEX IF NOT EXISTS ix_customer_perk_redemptions_order_id ON customer_perk_redemptions (order_id);
CREATE INDEX IF NOT EXISTS ix_customer_perk_redemptions_order_number ON customer_perk_redemptions (order_number);
CREATE INDEX IF NOT EXISTS ix_customer_perk_redemptions_campaign_id ON customer_perk_redemptions (campaign_id);
CREATE INDEX IF NOT EXISTS ix_customer_perk_redemptions_coupon_code ON customer_perk_redemptions (coupon_code);

