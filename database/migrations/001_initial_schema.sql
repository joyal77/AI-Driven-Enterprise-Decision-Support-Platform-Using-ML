ALTER TABLE prediction_batches ENABLE ROW LEVEL SECURITY;
ALTER TABLE data_integrity_audit_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE store_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE cart_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE churn_predictions ENABLE ROW LEVEL SECURITY;
ALTER TABLE retention_recommendations ENABLE ROW LEVEL SECURITY;
ALTER TABLE customer_retention_perks ENABLE ROW LEVEL SECURITY;
ALTER TABLE customer_notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE customer_perk_redemptions ENABLE ROW LEVEL SECURITY;

-- Catalog is publicly readable for customer shopping
DROP POLICY IF EXISTS "Public can view active products" ON products;
CREATE POLICY "Public can view active products" ON products FOR SELECT USING (true);

-- Backend service role and direct postgres connection bypass RLS by default.
-- All other tables reject anonymous direct access via Supabase REST Data API,
-- ensuring customer PII, predictions, orders, and credentials remain private.

